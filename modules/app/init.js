        /**
         * 13-1. 초기화 함수 (비동기: 데이터 로드 완료 후 UI 렌더링)
         */
        async function initializeApp() {
            console.log('🚀 애플리케이션 초기화 시작...');

            // 데이터 로드 (외부 JSON -> 로컬스토리지 -> 기본값 순서)
            await DataManager.loadData();

            // 프로젝트 선택 드롭다운 초기화
            const projectSelect = document.getElementById('current-project-select');
            DataStore.projects.forEach(proj => {
                const option = document.createElement('option');
                option.value = proj.id;
                option.textContent = proj.name;
                projectSelect.appendChild(option);
            });

            if (DataStore.projects.length > 0) {
                AppState.currentProjectId = DataStore.projects[0].id;
                projectSelect.value = AppState.currentProjectId;
            }

            // 역할 초기화
            AppState.currentRole = 'pm';
            document.getElementById('current-role-select').value = 'pm';
            UIController.updateUIByRole('pm');

            // 초기 화면 렌더링
            UIController.renderCurrentView();

            console.log('✅ 애플리케이션 초기화 완료');
            UIController.showToast('✅ 프로젝트 관리 시스템 v7 로드 완료', 'success');
        }

        // DOM 로드 완료 후 초기화
        if (document.readyState === 'loading') {
            document.addEventListener('DOMContentLoaded', initializeApp);
        } else {
            initializeApp();
        }

        // 다중 탭 동기화: 다른 탭에서 localStorage가 변경되면 데이터 재로드
        window.addEventListener('storage', (e) => {
            if (e.key === 'pmSystemData') {
                try {
                    DataManager.loadData();
                    UIController.renderCurrentView();
                    UIController.showToast('🔁 다른 탭의 변경 사항을 적용했습니다', 'info');
                } catch (err) {
                    console.error('storage sync failed', err);
                }
            }
        });

        console.log('✅ 전체 JavaScript 로딩 완료');